export function getStartPosition(level: number): { x: number; y: number } {
  const map = LEVEL_MAPS[level];
  if (map) {
    for (let y = 0; y < GRID_SIZE; y++) {
      for (let x = 0; x < GRID_SIZE; x++) {
        if (map[y]?.[x] === 3) return { x, y };
      }
    }
  }
  return { x: 4, y: 4 };
}

